-- 判断的"每 X 条群友消息才真跑一次"+ 最近一次读数（用户 2026-09-25）。
--
-- 问题：自主接话与冷场发起每次都要花一次判断模型调用，问的却是同一个问题（"这条消息值得接吗"）。
-- 群里连着来五条消息，就判五次；而判断结论只看"此刻这间会话值不值得开口"，短时间内几乎不会变。
--
-- 两处改动：
--
-- 1) `judgement_interval_turns`（默认 3，1–50）：距上一次真跑判断之后，这间会话又来了多少条群友消息。
--    没到 X 条就直接复用最近一次的分数（见下表），到了 X 条才真跑一次判断。1＝来一条新的群友消息就
--    问一次（与改动前最接近）；同一批消息重复判断时仍然复用。只作用于两条主动路径——直接回应与
--    连续交谈从来不跑判断。
--
-- 2) `qq_judgement_readings`：每会话一行"最近一次判断给出的分数"。分数是 0–10 的整数，配一个
--    **判断当时**的群友消息总数（差分就是"之后又来了几条"），再加判断时刻。**只存分数与计数**：
--    模型给的说明文字不落库（与裁决表同一条纪律：行内没有正文）。刻意不加指向 `qq_bindings` 的
--    外键——守卫是按会话收敛，加外键只会把"解绑"变成删除顺序问题（0030 的同一处决定）。
--
-- 3) 判断打分口径整体抬一档（用户同日第二次反馈：模型给的总分偏低）。程序规则在代码里，方案里那份
--    判断文案也要同步，否则"拿不准就给低分"会继续把分数往下压。这里把**从没被改过**的行换成新文案
--    （按 0035 写入的那份精确匹配），用户自己编辑过的判断文案一个字都不动。
ALTER TABLE qq_schemes ADD COLUMN judgement_interval_turns INTEGER NOT NULL DEFAULT 3 CHECK (judgement_interval_turns >= 1 AND judgement_interval_turns <= 50);

CREATE TABLE qq_judgement_readings (
  conversation_key TEXT NOT NULL PRIMARY KEY,
  score INTEGER NOT NULL CHECK (score >= 0 AND score <= 10),
  -- 判断当时这间会话的群友消息总数（只数群友，不数助手自己）。
  member_event_count INTEGER NOT NULL CHECK (member_event_count >= 0),
  judged_at_seconds INTEGER NOT NULL CHECK (judged_at_seconds >= 0)
);

