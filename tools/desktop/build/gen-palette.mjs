// Generates tools/desktop/src/DesktopPalette.g.cs from the single sources of truth:
//   - src/shared/appearance.ts  -> the 16 theme ids + their color / dark accents
//   - src/web/styles.css         -> the real :root (light) and .dark base tokens
// The desktop launcher must NOT hand-copy these values; this script keeps it in
// sync. Run before csc (the desktop build wires this in; see build.mjs).
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../../..");
const appearancePath = path.join(root, "src/shared/appearance.ts");
const cssPath = path.join(root, "src/web/styles.css");
const outPath = path.join(root, "tools/desktop/src/DesktopPalette.g.cs");

// parse the 16 themes from appearance.ts
const apTs = fs.readFileSync(appearancePath, "utf8");
const themes = [];
const themeRe = /id:\s*"([^"]+)"[^}]*?color:\s*"([^"]+)"[^}]*?dark:\s*"([^"]+)"/g;
let m = themeRe.exec(apTs);
while (m !== null) {
  themes.push({ id: m[1], color: m[2], dark: m[3] });
  m = themeRe.exec(apTs);
}
if (themes.length !== 16) {
  throw new Error(`expected 16 themes in appearance.ts, found ${themes.length}`);
}

// parse a CSS rule block and return its custom properties
const cssText = fs.readFileSync(cssPath, "utf8");
function blockVars(selector) {
  const idx = cssText.indexOf(selector);
  if (idx < 0) throw new Error(`CSS selector not found: ${selector}`);
  const start = cssText.indexOf("{", idx);
  let depth = 0;
  let i = start;
  for (; i < cssText.length; i++) {
    if (cssText[i] === "{") depth++;
    else if (cssText[i] === "}") {
      depth--;
      if (depth === 0) break;
    }
  }
  const body = cssText.slice(start + 1, i);
  const map = {};
  const vr = /(--[a-z0-9-]+)\s*:\s*([^;]+);/g;
  let v = vr.exec(body);
  while (v !== null) {
    map[v[1]] = v[2].trim();
    v = vr.exec(body);
  }
  return map;
}
const light = blockVars(":root {");
const dark = blockVars(":root.dark, .dark {");

function need(map, name, where) {
  if (!map[name]) throw new Error(`missing ${name} in ${where}`);
  return map[name];
}
const lightSurface = need(light, "--ac-surface", "light :root");
const lightText = need(light, "--ac-text", "light :root");
const lightMuted = need(light, "--ac-muted", "light :root");
const lightLine = need(light, "--superstring-tone-line", "light :root");
const lightSoft = need(light, "--superstring-tone-soft", "light :root");
const darkSurface = need(dark, "--ac-surface", "dark .dark");
const darkText = need(dark, "--ac-text", "dark .dark");
const darkMuted = need(dark, "--ac-muted", "dark .dark");
const darkLine = need(dark, "--superstring-tone-line", "dark .dark");
const darkSoft = need(dark, "--superstring-tone-soft", "dark .dark");

// emit C#5-compatible source
let themeConsts = "";
for (const t of themes) {
  themeConsts +=
    "        public const string " +
    Capitalize(t.id) +
    'Color = "' +
    t.color +
    '";\n' +
    "        public const string " +
    Capitalize(t.id) +
    'Dark = "' +
    t.dark +
    '";\n';
}
let idSwitch = "            switch (i) {\n";
let colorSwitch = '            if (id == "slate") return SlateColor;\n';
let darkSwitch = '            if (id == "slate") return SlateDark;\n';
themes.forEach((t, i) => {
  idSwitch += `                case ${i}: return "${t.id}";\n`;
  colorSwitch += `            if (id == "${t.id}") return ${Capitalize(t.id)}Color;\n`;
  darkSwitch += `            if (id == "${t.id}") return ${Capitalize(t.id)}Dark;\n`;
});
idSwitch += '                default: return "slate";\n            }';
colorSwitch += "            return SlateColor;";
darkSwitch += "            return SlateDark;";

const out =
  "// AUTO-GENERATED by tools/desktop/build/gen-palette.mjs. Do not edit by hand.\n" +
  "// Single source: src/shared/appearance.ts (16 themes) + src/web/styles.css (:root / .dark base tokens).\n" +
  "namespace Superstring.Desktop\n" +
  "{\n" +
  "    /// <summary>\n" +
  "    /// Resolved desktop colour source, generated from the project's single\n" +
  "    /// appearance sources. The 16 theme accents mirror web --ac-accent /\n" +
  "    /// --superstring-tone-deep (light = color, dark = dark variant). The base\n" +
  "    /// surface/text/muted/line/soft tokens are extracted verbatim from\n" +
  "    /// styles.css so the launcher matches the browser exactly.\n" +
  "    /// </summary>\n" +
  "    internal static class DesktopPalette\n" +
  "    {\n" +
  themeConsts +
  "        // Light base tokens (styles.css :root).\n" +
  '        public const string LightSurface = "' +
  lightSurface +
  '";\n' +
  '        public const string LightText = "' +
  lightText +
  '";\n' +
  '        public const string LightMuted = "' +
  lightMuted +
  '";\n' +
  '        public const string LightLine = "' +
  lightLine +
  '";\n' +
  '        public const string LightSoft = "' +
  lightSoft +
  '";\n' +
  "\n" +
  "        // Dark base tokens (styles.css .dark).\n" +
  '        public const string DarkSurface = "' +
  darkSurface +
  '";\n' +
  '        public const string DarkText = "' +
  darkText +
  '";\n' +
  '        public const string DarkMuted = "' +
  darkMuted +
  '";\n' +
  '        public const string DarkLine = "' +
  darkLine +
  '";\n' +
  '        public const string DarkSoft = "' +
  darkSoft +
  '";\n' +
  "\n" +
  "        public static int ThemeCount { get { return " +
  themes.length +
  "; } }\n" +
  "\n" +
  "        public static string ThemeIdAt(int i)\n" +
  "        {\n" +
  idSwitch +
  "\n" +
  "        }\n" +
  "\n" +
  "        public static string ThemeColor(string id)\n" +
  "        {\n" +
  colorSwitch +
  "\n" +
  "        }\n" +
  "\n" +
  "        public static string ThemeDark(string id)\n" +
  "        {\n" +
  darkSwitch +
  "\n" +
  "        }\n" +
  "    }\n" +
  "}\n";

fs.writeFileSync(outPath, out);
console.log(
  "Wrote " +
    outPath +
    " (" +
    themes.length +
    " themes; light surface " +
    lightSurface +
    ", dark surface " +
    darkSurface +
    ")",
);

function Capitalize(s) {
  return s.charAt(0).toUpperCase() + s.slice(1);
}
